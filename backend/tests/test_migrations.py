def test_course_column_failure_rolls_back_and_retries(tmp_path, monkeypatch):
    import pytest
    from alembic import op

    config = Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))
    engine = create_engine(f"sqlite:///{tmp_path / 'course-rollback.db'}")
    with engine.begin() as connection:
        config.attributes["connection"] = connection
        command.upgrade(config, "0008_material_exports")
        connection.exec_driver_sql(
            "INSERT INTO users (id,username,password_hash,timezone,created_at,updated_at) VALUES ('u','course-rollback','unused','Asia/Shanghai','2026-10-14','2026-10-14')"
        )
        connection.exec_driver_sql(
            "INSERT INTO courses (id,user_id,name,description,created_at,updated_at) VALUES ('c','u','原课程','原描述','2026-10-14','2026-10-14')"
        )
    original = op.add_column

    def injected(table, column, *args, **kwargs):
        if table == "courses" and column.name == "revision":
            raise RuntimeError("injected course column failure")
        return original(table, column, *args, **kwargs)

    with monkeypatch.context() as patch:
        patch.setattr(op, "add_column", injected)
        with pytest.raises(RuntimeError, match="injected course column failure"):
            with engine.begin() as connection:
                config.attributes["connection"] = connection
                command.upgrade(config, "head")
    with engine.connect() as connection:
        assert not {"category", "tags", "revision"} & {
            row[1] for row in connection.exec_driver_sql("PRAGMA table_info(courses)")
        }
        assert (
            connection.exec_driver_sql(
                "SELECT version_num FROM alembic_version"
            ).scalar()
            == "0008_material_exports"
        )
        assert connection.exec_driver_sql(
            "SELECT name,description FROM courses WHERE id='c'"
        ).one() == ("原课程", "原描述")
    with engine.begin() as connection:
        config.attributes["connection"] = connection
        command.upgrade(config, "head")
        assert connection.exec_driver_sql(
            "SELECT category,tags,revision FROM courses WHERE id='c'"
        ).one() == ("未分类", "[]", 1)
        assert connection.exec_driver_sql("PRAGMA foreign_key_check").all() == []


def test_asset_metadata_backfill_failure_is_atomic_and_can_retry(tmp_path, monkeypatch):
    import pytest
    from alembic import op

    config = Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))
    engine = create_engine(f"sqlite:///{tmp_path / 'asset-backfill.db'}")
    with engine.begin() as connection:
        connection.exec_driver_sql("PRAGMA foreign_keys=ON")
        config.attributes["connection"] = connection
        command.upgrade(config, "0006_manual_transcripts")
        connection.exec_driver_sql(
            "INSERT INTO users (id,username,password_hash,timezone,created_at,updated_at) VALUES ('u','backfill','unused','Asia/Shanghai','2026-10-14','2026-10-14')"
        )
        connection.exec_driver_sql(
            "INSERT INTO assets (id,user_id,original_filename,mime_type,size_bytes,sha256,storage_path,alt,deleted,created_at,updated_at) VALUES ('a','u','figure.png','image/png',1,'hash','figure.png','旧说明',0,'2026-10-14','2026-10-14')"
        )

    def fail_backfill(*args, **kwargs):
        raise RuntimeError("injected metadata backfill failure")

    with monkeypatch.context() as patch:
        patch.setattr(op, "execute", fail_backfill)
        with pytest.raises(RuntimeError, match="injected metadata backfill failure"):
            with engine.begin() as connection:
                config.attributes["connection"] = connection
                command.upgrade(config, "head")
    with engine.connect() as connection:
        assert "name" not in [
            row[1] for row in connection.exec_driver_sql("PRAGMA table_info(assets)")
        ]
        assert (
            connection.exec_driver_sql(
                "SELECT version_num FROM alembic_version"
            ).scalar()
            == "0006_manual_transcripts"
        )
        assert (
            connection.exec_driver_sql("SELECT alt FROM assets WHERE id='a'").scalar()
            == "旧说明"
        )
    with engine.begin() as connection:
        config.attributes["connection"] = connection
        command.upgrade(config, "head")
        assert (
            connection.exec_driver_sql("SELECT name FROM assets WHERE id='a'").scalar()
            == "figure.png"
        )
        assert connection.exec_driver_sql("PRAGMA foreign_key_check").all() == []


