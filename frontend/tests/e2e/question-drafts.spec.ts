import {test,expect} from '@playwright/test';
import {fileURLToPath} from 'node:url';
import {readFile} from 'node:fs/promises';

// All APIs in this test are real temporary APIs; fixed demo never calls a model.
for(const width of [390,1440])test(`M2候选：精确片段、固定演示、答案、导出与历史 ${width}px`,async({page,request})=>{
  await page.setViewportSize({width,height:1000});
  const base='http://127.0.0.1:8056/api/v1';
  const username='candidate_'+crypto.randomUUID().replaceAll('-','');
  const auth=await(await request.post(base+'/auth/register',{data:{username,password:'Test-password-2026'}})).json();
  const headers={Authorization:'Bearer '+auth.access_token};
  const course=await(await request.post(base+'/courses',{headers,data:{name:'M2候选自制验收'}})).json();
  const bytes=await readFile(fileURLToPath(new URL('../../../fixtures/materialhub_demo.md',import.meta.url)));
  const upload=await(await request.post(base+`/courses/${course.id}/documents`,{headers,multipart:{file:{name:'演示资料.md',mimeType:'text/markdown',buffer:bytes}}})).json();
  const version=upload.resource_id;
  await expect.poll(async()=>(await(await request.get(base+`/versions/${version}`,{headers})).json()).index_status).toBe('SUCCEEDED');
  await request.post(base+`/courses/${course.id}/topics`,{headers,data:{name:'进程与线程'}});
  await page.addInitScript(({token,username})=>{localStorage.setItem('hustudy_token',token);localStorage.setItem('hustudy_user',username);},{token:auth.access_token,username});
  await page.goto(`/ai?course=${course.id}`);
  await page.getByRole('button',{name:'练习题生成',exact:true}).click();
  const demo=page.getByRole('button',{name:'运行固定自制演示（不发送）',exact:true});
  await expect(demo).toBeDisabled();
  await page.getByRole('checkbox',{name:/演示资料/}).check();
  await page.getByRole('checkbox',{name:'进程与线程',exact:true}).check();
  await page.getByLabel('题数',{exact:true}).fill('2');
  await page.getByLabel('每题分值',{exact:true}).fill('2.50');
  await page.getByText('精确选择片段 · 可选',{exact:true}).click();
  await page.getByRole('button',{name:'读取可选片段',exact:true}).click();
  await page.getByLabel('查找片段',{exact:true}).fill('进程是资源分配');
  await page.getByRole('checkbox',{name:/进程是资源分配/}).check();
  await demo.click();
  const article=page.getByRole('article',{name:'题目候选草稿'});
  await expect(article).toBeVisible();await expect(article).toContainText('第2题');
  await expect(article).toContainText('无真题参考');
  await article.getByText('查看参考答案与评分细则',{exact:true}).first().click();
  await expect(article).toContainText('原文区分了进程');
  const received=page.waitForEvent('download');
  await article.getByRole('button',{name:'导出题目草稿（JSON）',exact:true}).click();
  const download=await received;const result=JSON.parse(await readFile((await download.path())!,'utf8'));
  expect(result.model_mode).toBe('demo');expect(result.result.question_drafts).toHaveLength(2);
  expect(result.result.question_drafts[0].points).toBe(2.5);
  expect(result.result.question_drafts[0].generation_status).toBe('draft');
  expect(result.result.coverage.versions[0].selected_chunks).toBe(1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:fileURLToPath(new URL(`../../../docs/gcx/evidence/question-drafts-${width}.png`,import.meta.url)),fullPage:true});
  await page.reload();await page.getByRole('button',{name:'练习题生成',exact:true}).click();
  await page.locator('.report-history').getByRole('button',{name:/查看结果/}).first().click();
  await expect(article).toBeVisible();
  await page.getByRole('button',{name:'学习报告',exact:true}).click();
  await page.getByRole('checkbox',{name:/演示资料/}).check();
  await page.getByRole('button',{name:'运行固定报告演示（不发送）',exact:true}).click();
  const teaching=page.getByRole('article',{name:'章节学习报告'});
  await expect(teaching).toBeVisible();await expect(teaching).toContainText('本次学习目标');
  await expect(teaching).toContainText('知识点分层目录');
  await expect(teaching).toContainText('概念关系与难点突破');
  await expect(teaching).toContainText('复习建议');
  await expect(teaching.locator('.report-exercise')).toHaveCount(3);
});
