import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
test('首卷默认选择、手选刷新保持、重复录入保留和完整样例下载',async({page,request})=>{
 const base='http://127.0.0.1:8056/api/v1';
 const auth=await(await request.post(base+'/auth/register',{data:{username:'bankux_'+crypto.randomUUID().replaceAll('-',''),password:'Synthetic-password-2026'}})).json();
 const headers={Authorization:'Bearer '+auth.access_token};
 const course=await(await request.post(base+'/courses',{headers,data:{name:'题库体验验收'}})).json();
 const papers=[];for(const title of ['先上传卷','后上传卷'])papers.push(await(await request.post(`${base}/courses/${course.id}/question-bank/import`,{headers,data:{title,content:'1. 两份卷保留同一道题。\n知识标签：综合'}})).json());
 expect(papers[0].id).not.toBe(papers[1].id);
 await page.addInitScript(a=>{localStorage.setItem('hustudy_token',a.access_token);localStorage.setItem('hustudy_user',a.user.username);},auth);
 await page.route("**/question-bank/ai-jobs",route=>route.fulfill({json:[{paper_id:papers[0].id,title:"旧完成任务",status:"SUCCEEDED",model:"test",endpoint:"https://example.invalid",expires_at:"2099-01-01"}]}));
 await page.goto(`/exam?course=${course.id}`);
 const select=page.getByLabel('显示题库',{exact:true});await expect(select).toHaveValue(papers[1].id);
 await expect(page.locator('.bank-question-editor')).toHaveCount(1);
 await expect(page.getByRole('button',{name:'AI图片识别（可选）',exact:true})).toHaveCount(0);
 await expect(page.getByLabel('选择题目图片（PNG/JPEG/WebP，可多选）')).toHaveCount(0);
 const promise=page.waitForEvent('download');await page.getByRole('button',{name:'下载完整Markdown样例',exact:true}).click();
 const file=await promise;expect(file.suggestedFilename()).toBe('Hustudy-题库完整样例.md');
 const path=resolve('../local/m4-complete-template.md');await file.saveAs(path);
 const raw=readFileSync(path,'utf8');expect(raw).toBe(readFileSync(resolve('src/features/exams/bankExample.md'),'utf8'));
 expect(raw).toContain('| --- |');expect(raw).toContain('\\oplus');
 await page.getByText('预览样例公式与表格',{exact:true}).click();
 const example=page.getByRole('region',{name:'严格Markdown完整样例'});
 await expect(example.locator('table').first()).toBeVisible();await expect(example.locator('.katex').first()).toBeVisible();
 await expect(example.locator('.katex-error')).toHaveCount(0);
 await select.selectOption(papers[0].id);await expect(select).toHaveValue(papers[0].id);
 await page.locator('.bank-question-editor').first().getByRole('button',{name:'保存本题校正',exact:true}).click();
 await expect(page.getByText('已保存校正，请核验修改后的题目',{exact:true})).toBeVisible();
 await expect(select).toHaveValue(papers[0].id);
 await page.reload();await expect(select).toHaveValue(papers[1].id);
 await page.getByRole('button',{name:'考点、统计与蓝图',exact:true}).click();
 await page.getByRole('button',{name:'上传与校正题库',exact:true}).click();
 await expect(select).toHaveValue(papers[1].id);
});
