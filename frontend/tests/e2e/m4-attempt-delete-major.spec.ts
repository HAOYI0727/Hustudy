import {test,expect} from '@playwright/test';
const base='http://127.0.0.1:8056/api/v1';
for(const width of [1440,390])test(`大题整卷与删除作答 ${width}`,async({page,request})=>{
 await page.setViewportSize({width,height:1000});
 const auth=await(await request.post(base+'/auth/register',{data:{username:'major_'+crypto.randomUUID().replaceAll('-',''),password:'Synthetic-password-2026'}})).json();
 const headers={Authorization:'Bearer '+auth.access_token};
 const course=await(await request.post(base+'/courses',{headers,data:{name:'隔离大题验收'}})).json();
 const source=await(await request.post(`${base}/courses/${course.id}/question-bank/import`,{headers,data:{title:'大题样例',content:'1. 公共条件：内存8KB，计算 $2^3$。\n\n| 地址 | 数值 |\n| --- | --- |\n| 0 | 2 |\n答案：父题答案保密\n2. 第二大题独立题干。\n知识标签：综合'}})).json();
 const parent=source.questions.find((q:any)=>q.number==='1');
 const split=await request.post(`${base}/past-questions/${parent.id}/split`,{headers,data:{revision:parent.revision,parts:['计算地址。\n答案：第一问答案保密','解释过程。\n答案：第二问答案保密']}});
 expect(split.ok()).toBeTruthy();
 expect((await request.post(`${base}/past-papers/${source.id}/confirm`,{headers})).ok()).toBeTruthy();
 await page.addInitScript(a=>{localStorage.setItem('hustudy_token',a.access_token);localStorage.setItem('hustudy_user',a.user.username);},auth);
 await page.goto(`/exam?course=${course.id}`);await page.getByRole('button',{name:'题库练习与作答',exact:true}).click();
 await page.getByLabel('选择练习方式',{exact:true}).selectOption('whole');
 await page.getByLabel('选择题库试卷',{exact:true}).selectOption(source.id);
 await page.getByRole('button',{name:'载入整套试卷',exact:true}).click();
 const groups=page.locator('.bank-major-question');await expect(groups).toHaveCount(2);
 const first=groups.first();await expect(first.locator('.question-card')).toHaveCount(2);
 await expect(first.getByRole('region',{name:'整道题目',exact:true})).toHaveCount(1);
 await expect(first.getByRole('table')).toBeVisible();await expect(first.locator('.katex').first()).toBeVisible();
 await expect(first).toContainText('计算地址');await expect(first).toContainText('解释过程');
 await expect(page.getByRole('button',{name:'查看整道题'})).toHaveCount(0);
 await expect(first).not.toContainText('答案保密');
 await page.getByRole('button',{name:'已核对题干，确认练习'}).click();await page.getByRole('button',{name:'开始作答',exact:true}).click();
 await expect(first.getByLabel('解答内容')).toHaveCount(2);
 await page.screenshot({path:`../local/m4-major-unit-${width}.png`,fullPage:true});
 await first.getByLabel('解答内容').first().fill('待保存答案');
 page.once('dialog',dialog=>dialog.dismiss());await page.getByRole('button',{name:'删除当前作答记录',exact:true}).click();
 await expect(first.getByLabel('解答内容').first()).toHaveValue('待保存答案');
 await first.getByRole('button',{name:'保存本题答案'}).first().click();
 await page.getByRole('button',{name:'交卷并查看答案'}).click();
 await first.getByRole('button',{name:'我答错了',exact:true}).first().click();
 const mistakes=await(await request.get(base+'/mistakes',{headers})).json();expect(mistakes).toHaveLength(1);
 const plan=await request.post(base+'/review-tasks',{headers,data:{title:'删除关联复习',mistake_id:mistakes[0].id}});expect(plan.ok()).toBeTruthy();
 const records=await(await request.get(`${base}/courses/${course.id}/exam-papers`,{headers})).json();
 const id=records[0].attempts[0].id;
 await page.locator('.bank-practice-history summary').click();
 page.once('dialog',dialog=>{expect(dialog.message()).toContain('复习计划');dialog.accept();});
 await page.getByRole('button',{name:'删除第1次作答记录',exact:true}).click();
 await expect(page.getByText('作答记录及关联错题、复习计划已删除',{exact:true})).toBeVisible();
 expect((await request.get(`${base}/attempts/${id}`,{headers})).status()).toBe(404);
 expect(await(await request.get(base+'/mistakes',{headers})).json()).toHaveLength(0);
 expect((await(await request.get(base+'/review-tasks',{headers})).json()).items).toHaveLength(0);
 await expect(page.getByRole('button',{name:'删除当前作答记录',exact:true})).toBeDisabled();
 await page.reload();await page.getByRole('button',{name:'题库练习与作答',exact:true}).click();
 await expect(page.locator('.question-card')).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
});
