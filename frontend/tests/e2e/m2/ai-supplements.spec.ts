import {test,expect} from '@playwright/test';

for(const width of [390,1440])test(`补充笔记与自动标签零记录回退 ${width}px`,async({page,request})=>{
  test.setTimeout(90000);
  await page.setViewportSize({width,height:1000});
  const base='http://127.0.0.1:8056/api/v1';
  const username='supplement_'+crypto.randomUUID().replaceAll('-','');
  const auth=await(await request.post(base+'/auth/register',{data:{username,password:'Test-password-2026'}})).json();
  const headers={Authorization:'Bearer '+auth.access_token};
  const course=await(await request.post(base+'/courses',{headers,data:{name:'M2补充依据验收'}})).json();
  const upload=await(await request.post(base+`/courses/${course.id}/documents`,{headers,multipart:{file:{name:'课堂资料.md',mimeType:'text/markdown',buffer:Buffer.from('# 数量\n\n两个苹果加三个苹果等于五个苹果。')}}})).json();
  const version=upload.resource_id;
  await expect.poll(async()=>(await(await request.get(base+`/versions/${version}`,{headers})).json()).index_status).toBe('SUCCEEDED');
  const chunk=(await(await request.get(base+`/versions/${version}/chunks`,{headers})).json())[0];
  const note=await(await request.post(base+'/notes',{headers,data:{title:'课堂补充笔记',content:'我的自制笔记：加法是数量合并。',course_id:course.id}})).json();
  const citation={version_id:version,chunk_id:chunk.id,quote:chunk.text,availability:'active',locator:{type:'heading',value:'数量'}};
  let confirms=0,previews=0;
  const pending:any={id:crypto.randomUUID(),course_id:course.id,query:'理解所选资料，梳理知识点并完成自测',request_kind:'study_report',model:'glm-5.3-flash',endpoint:'https://open.bigmodel.cn/api/paas/v4/chat/completions',expires_at:new Date(Date.now()+900000).toISOString(),consented_at:null,dispatched_at:null,sources:[{source_id:chunk.id,version_id:version,document_name:'课堂资料.md',version_no:1,locator:citation.locator,text:chunk.text}],job:null,result:null};
  await page.route('**/api/v1/ai/provider',route=>route.fulfill({json:{configured:true,model:pending.model}}));
  await page.route(`**/api/v1/courses/${course.id}/study-reports/preview`,async route=>{
    previews++;const sent=route.request().postDataJSON();
    expect(sent.note_ids).toEqual([note.id]);expect(sent.notes_confirmed).toBe(true);
    expect(sent).not.toHaveProperty("teacher_marks");expect(sent).not.toHaveProperty("exam_paper_ids");expect(sent).not.toHaveProperty("exam_sources_confirmed");
    pending.sources[0].m2_supplement={version:2,automatic_report_sources:true,notes:[note],teacher_marks:[],exam_evidence:[]};
    await route.fulfill({status:201,json:pending});
  });
  await page.route(`**/api/v1/remote-queries/${pending.id}/confirm`,async route=>{
    confirms++;
    const exercise={question:'数量如何相加？',answer:'将数量合并。',citations:[citation]};
    pending.job={status:'SUCCEEDED'};
    pending.result={id:crypto.randomUUID(),course_id:course.id,query:pending.query,status:'grounded',model_mode:'real',result:{citations:[citation],m2_supplement:pending.sources[0].m2_supplement,study_report:{summary:'数量加法',learning_goals:['理解数量'],prerequisites:[],learning_sequence:['先读原文'],topics:[{topic_id:crypto.randomUUID(),name:'加法',explanation:exercise.answer,misconceptions:[],labels:[{kind:'key',origin:'ai_suggestion',reason:'依据原文提出学习建议'}],citations:[citation]}],examples:[exercise],self_checks:[exercise,exercise,exercise]}}};
    await route.fulfill({json:pending});
  });
  await page.addInitScript(({token,username})=>{localStorage.setItem('hustudy_token',token);localStorage.setItem('hustudy_user',username);},{token:auth.access_token,username});
  await page.goto(`/ai?course=${course.id}`);
  await page.getByRole('button',{name:'学习报告',exact:true}).click();
  await page.getByRole('checkbox',{name:/课堂资料/}).check();
  await page.locator('summary').filter({hasText:'补充笔记 · 可选'}).click();
  await page.getByRole('button',{name:'查找课程笔记',exact:true}).click();
  await page.getByRole('checkbox',{name:'课堂补充笔记',exact:true}).check();
  await page.getByRole('button',{name:'核对正文',exact:true}).click();
  await expect(page.locator('pre')).toContainText(note.content);
  await page.getByRole('checkbox',{name:/我已核对选中笔记/}).check();
  await expect(page.getByRole('button',{name:'读取对应原文',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'查找已核验题库',exact:true})).toHaveCount(0);
  await expect(page.getByRole('textbox',{name:'课堂强调说明',exact:true})).toHaveCount(0);
  expect(confirms).toBe(0);expect(previews).toBe(0);
  await page.getByRole('button',{name:'预览将发送的片段',exact:true}).click();
  await expect(page.getByText('个人补充笔记：课堂补充笔记',{exact:false})).toBeVisible();
  await expect(page.getByRole('button',{name:'确认本次发送',exact:true})).toBeDisabled();
  await page.getByRole('checkbox',{name:/我已核对上述问题与片段/}).check();
  await page.getByRole('button',{name:'确认本次发送',exact:true}).click();
  await expect(page.locator('#ai-result')).toContainText('重点 · AI建议');
  await expect(page.locator('#ai-result')).not.toContainText('重点 · 教师强调');
  expect(confirms).toBe(1);
  const unchanged=await(await request.get(base+`/notes/${note.id}`,{headers})).json();
  expect(unchanged.revision).toBe(note.revision);expect(unchanged.content).toBe(note.content);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
